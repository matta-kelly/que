/**
 * Multi-select for chats. Provided by the sidebar's Chats section; when
 * `selecting`, rows show checkboxes and clicking toggles instead of opening.
 */
export type ChatSelection = {
  selecting: boolean;
  selected: ReadonlySet<string>;
  toggle: (id: string) => void;
  start: (id: string) => void;
};
export const ChatSelectionContext = createContext<ChatSelection | null>(null);

const ThreadListItem: FC = () => {
  const isRunning = useAuiState((s) => s.threadListItem.isRunning);
  const id = useAuiState((s) => s.threadListItem.id);
  const selection = useContext(ChatSelectionContext);
  const openChat = useOpenChat();
  const [isRenaming, setIsRenaming] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const restoreFocusRef = useRef(false);

  useEffect(() => {
    if (isRenaming || !restoreFocusRef.current) return;
    restoreFocusRef.current = false;
    triggerRef.current?.focus();
  }, [isRenaming]);

  return (
    <ThreadListItemPrimitive.Root
      data-slot="aui_thread-list-item"
      className="group hover:bg-muted focus-visible:bg-muted data-active:bg-muted has-focus-visible:bg-muted has-data-[state=open]:bg-muted relative flex h-8 items-center rounded-md transition-colors focus-visible:outline-none"
    >
      {selection?.selecting ? (
        <button
          type="button"
          role="checkbox"
          aria-checked={selection.selected.has(id)}
          data-slot="aui_thread-list-item-select"
          onClick={() => selection.toggle(id)}
          className="flex h-full min-w-0 flex-1 items-center gap-2 rounded-md px-2.5 text-start text-[13px] outline-none"
        >
          <span
            className={cn(
              "flex size-3.5 shrink-0 items-center justify-center rounded-[4px] border",
              selection.selected.has(id)
                ? "bg-primary border-primary text-primary-foreground"
                : "border-muted-foreground/50",
            )}
          >
            {selection.selected.has(id) && <CheckIcon className="size-3" />}
          </span>
          <span
            data-slot="aui_thread-list-item-title"
            className="min-w-0 flex-1 truncate"
          >
            <ThreadListItemPrimitive.Title fallback="New Chat" />
          </span>
        </button>
      ) : isRenaming ? (
        <ThreadListItemRename
          onDone={(restoreFocus) => {
            restoreFocusRef.current = restoreFocus;
            setIsRenaming(false);
          }}
        />
      ) : (
        <ThreadListItemPrimitive.Trigger
          ref={triggerRef}
          // Opens the chat on the chat page, even from another page (Reports,
          // …); preventDefault skips the primitive's own switch, which
          // useOpenChat already does.
          onClick={(e) => {
            e.preventDefault();
            openChat(id);
          }}
          data-slot="aui_thread-list-item-trigger"
          className="focus-visible:ring-ring/50 flex h-full min-w-0 flex-1 items-center rounded-md px-2.5 text-start text-[13px] outline-none group-hover:pe-9 group-has-focus-visible:pe-9 group-has-data-[state=open]:pe-9 group-data-active:pe-9 focus-visible:ring-1"
        >
          {isRunning && (
            <Loader2Icon
              aria-hidden
              data-slot="aui_thread-list-item-running"
              className="text-muted-foreground me-1.5 size-3.5 shrink-0 animate-spin"
            />
          )}
          <span
            data-slot="aui_thread-list-item-title"
            className="min-w-0 flex-1 truncate"
          >
            <ThreadListItemPrimitive.Title fallback="New Chat" />
          </span>
          {isRunning && <span className="sr-only">Running</span>}
        </ThreadListItemPrimitive.Trigger>
      )}
      {!selection?.selecting && (
        <ThreadListItemMore
          onRename={() => setIsRenaming(true)}
          onSelect={() => selection?.start(id)}
        />
      )}
    </ThreadListItemPrimitive.Root>
  );
};

const ThreadListItemRename: FC<{
  onDone: (restoreFocus: boolean) => void;
}> = ({ onDone }) => {
  const aui = useAui();
  const title = useAuiState((s) => s.threadListItem.title) ?? "";
  const [value, setValue] = useState(title);
  const inputRef = useRef<HTMLInputElement>(null);
  const settledRef = useRef(false);

  useEffect(() => {
    inputRef.current?.select();
  }, []);

  const commit = (restoreFocus: boolean) => {
    if (settledRef.current) return;
    settledRef.current = true;

    const next = value.trim();
    if (!next || next === title) {
      onDone(restoreFocus);
      return;
    }

    // Close right away and save in the background, so the row doesn't sit in
    // edit mode waiting on the server. Deferred so a synchronous throw lands
    // on the rejection path too.
    onDone(restoreFocus);
    Promise.resolve()
      .then(() => aui.threadListItem.rename(next))
      .catch(() =>
        toast("Couldn't rename the chat", { description: "Please try again." }),
      );
  };

  const cancel = () => {
    if (settledRef.current) return;
    settledRef.current = true;
    onDone(true);
  };

  return (
    <Input
      ref={inputRef}
      autoFocus
      data-slot="aui_thread-list-item-rename"
      aria-label="Rename thread"
      placeholder="Name this chat"
      value={value}
      className="h-7 min-w-0 flex-1 ps-2.5 pe-9 text-sm"
      onChange={(event) => setValue(event.target.value)}
      onBlur={() => commit(false)}
      onKeyDown={(event) => {
        if (event.key === "Enter") {
          event.preventDefault();
          commit(true);
        } else if (event.key === "Escape") {
          event.preventDefault();
          cancel();
        }
      }}
    />
  );
};

